/// One ggplot2 conformance row: the grammar its R oracle was generated with. A row exists here
/// only if its contract names an oracle with an `expected*.json` and at least one falsification
/// test (the build script refuses the build otherwise).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct ProvenRow {
    /// Contract id, e.g. `ggplot2-row1-point-v1`.
    pub contract: &'static str,
    /// The row's name, e.g. `geom_point`.
    pub name: &'static str,
    /// Geom of the layer.
    pub geom: &'static str,
    /// Stat of the layer.
    pub stat: &'static str,
    /// Position of the layer.
    pub position: &'static str,
    /// `(aesthetic, scale type)` per position scale.
    pub scales: &'static [(&'static str, &'static str)],
    /// Coordinate system.
    pub coord: &'static str,
    /// Facet (`null` is ggplot2's `facet_null()`, one panel).
    pub facet: &'static str,
    /// Theme (`grey` is ggplot2's default `theme_grey()`).
    pub theme: &'static str,
    /// Aesthetics mapped.
    pub aes: &'static [&'static str],
}

/// The rows the verb draws, generated from the contracts by `build.rs`.
pub const PROVEN_ROWS: &[ProvenRow] = include!("proven_rows.rs");

/// ggplot2 spells some names two ways (`theme_gray` is `theme_grey`); `(alias, name)`.
const ALIASES: &[(&str, &str)] = &[("gray", "grey")];

/// Distinct values in first-seen order, then the aliases of those values.
fn distinct(values: impl IntoIterator<Item = &'static str>) -> Vec<&'static str> {
    let mut out: Vec<&'static str> = Vec::new();
    for v in values {
        if !out.contains(&v) {
            out.push(v);
        }
    }
    let aliases = ALIASES.iter().filter(|(_, name)| out.contains(name));
    let aliases: Vec<&'static str> = aliases.map(|(alias, _)| *alias).collect();
    out.extend(aliases);
    out
}

fn rows_with(geom: &str) -> impl Iterator<Item = &'static ProvenRow> + '_ {
    PROVEN_ROWS.iter().filter(move |r| r.geom == geom)
}

/// Geoms of the proven rows.
pub fn geoms() -> Vec<&'static str> {
    distinct(PROVEN_ROWS.iter().map(|r| r.geom))
}

/// Stats proven with `geom`.
pub fn stats(geom: &str) -> Vec<&'static str> {
    distinct(rows_with(geom).map(|r| r.stat))
}

/// Positions proven with `geom`.
pub fn positions(geom: &str) -> Vec<&'static str> {
    distinct(rows_with(geom).map(|r| r.position))
}

/// Aesthetics that have a proven position scale.
pub fn scale_aesthetics() -> Vec<&'static str> {
    distinct(PROVEN_ROWS.iter().flat_map(|r| r.scales.iter().map(|s| s.0)))
}

/// Scale types proven for aesthetic `aes`.
pub fn scales(aes: &str) -> Vec<&'static str> {
    let of = |r: &'static ProvenRow| r.scales.iter().filter(|s| s.0 == aes).map(|s| s.1);
    distinct(PROVEN_ROWS.iter().flat_map(of))
}

/// Aesthetics the proven rows map.
pub fn aesthetics() -> Vec<&'static str> {
    distinct(PROVEN_ROWS.iter().flat_map(|r| r.aes.iter().copied()))
}

/// Coordinate systems of the proven rows.
pub fn coords() -> Vec<&'static str> {
    distinct(PROVEN_ROWS.iter().map(|r| r.coord))
}

/// Facets of the proven rows.
pub fn facets() -> Vec<&'static str> {
    distinct(PROVEN_ROWS.iter().map(|r| r.facet))
}

/// Themes of the proven rows, with their alternative spellings.
pub fn themes() -> Vec<&'static str> {
    distinct(PROVEN_ROWS.iter().map(|r| r.theme))
}

/// The engine geom for a proven geom name. Every proven geom needs an arm here; a test walks
/// [`PROVEN_ROWS`] to keep it so.
fn geom_for(name: &str) -> Result<Geom, String> {
    match name {
        "point" => Ok(Geom::point()),
        other => Err(format!("geom '{other}' is proven but the plot verb has no builder for it")),
    }
}

/// Layers a proven row draws: a row names one geom, so it proves one layer.
const ROW_LAYERS: usize = 1;

/// The spelling a row uses for a name that has an alias (`gray` is `grey`).
fn canonical(name: &str) -> &str {
    ALIASES.iter().find(|(alias, _)| *alias == name).map_or(name, |(_, real)| real)
}

/// The layer's own choices fit the row. An unset stat or position is the row's.
fn layer_fits(row: &ProvenRow, layer: &LayerSpec) -> bool {
    row.geom == layer.geom
        && layer.stat.as_deref().map_or(true, |s| s == row.stat)
        && layer.position.as_deref().map_or(true, |p| p == row.position)
}

/// Every scale, aesthetic and coord the spec names is one this row proves.
fn scales_fit(row: &ProvenRow, spec: &Spec) -> bool {
    spec.scales.iter().all(|(a, t)| row.scales.iter().any(|s| s.0 == a && s.1 == t))
        && spec.aes.keys().all(|a| row.aes.contains(&a.as_str()))
        && spec.coord.as_ref().map_or(true, |c| c.kind == row.coord)
}

/// The facet and theme the spec names are the row's.
fn panel_fits(row: &ProvenRow, spec: &Spec) -> bool {
    let facet = match &spec.facet {
        None => true,
        Some(FacetSpec::Name(f)) => f == row.facet,
        Some(FacetSpec::Other(_)) => false,
    };
    facet && spec.theme.as_deref().map_or(true, |t| canonical(t) == row.theme)
}

/// The one proven row the spec asks for. The per-value checks of [`check_spec`] test each
/// value against the union of all rows; this tests the combination against each row, so a
/// scale proven only with another geom, or a second layer, is refused.
fn select_row<'a>(rows: &'a [ProvenRow], spec: &Spec) -> Result<&'a ProvenRow, String> {
    let [layer] = spec.layers.as_slice() else {
        return Err(format!(
            "the plot has {} layers; each proven ggplot2 row draws {ROW_LAYERS}",
            spec.layers.len()
        ));
    };
    rows.iter()
        .find(|r| layer_fits(r, layer) && scales_fit(r, spec) && panel_fits(r, spec))
        .ok_or_else(|| {
            let names: Vec<&str> = rows.iter().map(|r| r.name).collect();
            format!(
                "no proven ggplot2 row draws this combination of geom, stat, position, scales, \
                 coord, facet, theme and aesthetics; proven rows: {}",
                names.join(", ")
            )
        })
}

fn no_builder(kind: &str, name: &str) -> String {
    format!("{kind} '{name}' is proven but the plot verb has no builder for it")
}

/// The engine stat for a proven stat name.
fn stat_for(name: &str) -> Result<Stat, String> {
    match name {
        "identity" => Ok(Stat::Identity),
        other => Err(no_builder("stat", other)),
    }
}

/// Every layer the engine draws is placed as it is (`identity`).
fn position_for(name: &str) -> Result<(), String> {
    match name {
        "identity" => Ok(()),
        other => Err(no_builder("position", other)),
    }
}

/// The engine trains continuous position scales on x and y and nothing else.
fn scale_for(aes: &str, kind: &str) -> Result<(), String> {
    match (aes, kind) {
        ("x" | "y", "continuous") => Ok(()),
        _ => Err(no_builder("scale", &format!("{aes}: {kind}"))),
    }
}

/// The engine draws one panel (`facet_null()`); no other facet has a builder.
fn facet_for(name: &str) -> Result<(), String> {
    match name {
        "null" => Ok(()),
        other => Err(no_builder("facet", other)),
    }
}

/// The engine maps `x` and `y` and no other aesthetic.
fn aes_for(aes: &[&str]) -> Result<(), String> {
    match aes {
        ["x", "y"] => Ok(()),
        other => Err(no_builder("aes", &other.join(" "))),
    }
}

/// The engine coord for a proven coord name.
fn coord_for(name: &str) -> Result<Coord, String> {
    match name {
        "cartesian" => Ok(Coord::cartesian()),
        other => Err(no_builder("coord", other)),
    }
}

/// The engine theme for a proven theme name.
fn theme_for(name: &str) -> Result<Theme, String> {
    match name {
        "grey" => Ok(Theme::grey()),
        other => Err(no_builder("theme", other)),
    }
}

/// Refuse the coords the rows do not prove, and the zoom limits no row proves: they set the
/// panel's scale range and breaks, which ggplot2 computes differently from the data-trained
/// ones the engine keeps.
fn check_coord(coord: Option<&CoordSpec>) -> Result<(), String> {
    let Some(c) = coord else {
        return Ok(());
    };
    check("coord", Some(&c.kind), &coords())?;
    for (name, lim) in [("xlim", c.xlim), ("ylim", c.ylim)] {
        if lim.is_some() {
            return Err(format!("coord limits ({name}) are not proven by any ggplot2 row"));
        }
    }
    Ok(())
}
/// Terminal size when stdout is not a terminal, or when a terminal does not say its size.
pub const DEFAULT_TERM_SIZE: (u32, u32) = (80, 24);
/// SVG size in pixels when none is given (ggplot2's 800x600 preview in aprender-viz).
pub const DEFAULT_SVG_SIZE: (u32, u32) = (800, 600);
/// Smallest SVG side in pixels.
pub const MIN_SVG_SIZE: u32 = 1;
/// Largest SVG side in pixels. The engine rasterises points into a width x height pixel
/// buffer, so an unbounded size is an unbounded allocation.
pub const MAX_SVG_SIZE: u32 = 4096;

/// Where the plot goes.
#[derive(Debug, Clone, Copy, PartialEq, Eq, clap::ValueEnum)]
pub enum Output {
    /// Unicode text for a terminal.
    Term,
    /// An SVG document.
    Svg,
}

/// Arguments of `apr plot` and `aprender-present plot`.
#[derive(Debug, Clone, clap::Args)]
pub struct PlotArgs {
    /// YAML plot spec (data, aes, layers, scales, coord, facet, labs, theme)
    #[arg(long, conflicts_with_all = ["data", "aes", "geom"])]
    pub spec: Option<ConfigPath>,

    /// CSV file with a header row (`#` lines are skipped). Values are zero or have a magnitude
    /// from 1e-5 up to but excluding 1e16, the span whose axis labels were compared with ggplot2
    #[arg(long, required_unless_present = "spec")]
    pub data: Option<InputFile>,

    /// Aesthetic mappings, e.g. x=height,y=weight
    #[arg(long, required_unless_present = "spec")]
    pub aes: Option<FreeText>,

    /// Geom of the single layer, one of the proven geoms [default: point]
    #[arg(long)]
    pub geom: Option<FreeText>,

    /// Plot title (overrides the spec's labs.title)
    #[arg(long)]
    pub title: Option<FreeText>,

    /// x-axis label (overrides labs.x)
    #[arg(long)]
    pub xlab: Option<FreeText>,

    /// y-axis label (overrides labs.y)
    #[arg(long)]
    pub ylab: Option<FreeText>,

    /// Width: cells for term, pixels for svg
    #[arg(long)]
    pub width: Option<u32>,

    /// Height: lines for term, pixels for svg
    #[arg(long)]
    pub height: Option<u32>,

    /// Render target
    #[arg(long, value_enum, default_value_t = Output::Term)]
    pub output: Output,

    /// Write to this file instead of stdout
    #[arg(long)]
    pub out: Option<OutputPath>,

    /// Never emit colour escape sequences
    #[arg(long)]
    pub no_color: bool,
}

/// The process facts that decide size and colour, read once so tests can set them.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Env {
    /// stdout is a terminal.
    pub stdout_is_tty: bool,
    /// `$COLUMNS`.
    pub columns: Option<String>,
    /// `$LINES`.
    pub lines: Option<String>,
    /// `$NO_COLOR` is set to a non-empty value (<https://no-color.org>).
    pub no_color: bool,
}

impl Env {
    /// Read the facts from this process.
    pub fn from_process() -> Self {
        use std::io::IsTerminal;
        Self {
            stdout_is_tty: std::io::stdout().is_terminal(),
            columns: std::env::var("COLUMNS").ok(),
            lines: std::env::var("LINES").ok(),
            no_color: !std::env::var_os("NO_COLOR").unwrap_or_default().is_empty(),
        }
    }
}

/// The YAML spec. Unknown keys are errors, so a typo is not silently ignored.
#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Spec {
    /// CSV path, relative to the spec file.
    pub data: PathBuf,
    /// Global aesthetic mappings.
    pub aes: BTreeMap<String, String>,
    /// Layers, drawn in order.
    pub layers: Vec<LayerSpec>,
    /// Position scales, `x:`/`y:` -> scale type.
    #[serde(default)]
    pub scales: BTreeMap<String, String>,
    /// Coordinate system.
    #[serde(default)]
    pub coord: Option<CoordSpec>,
    /// Facet (only `null`). Any other value, a name or a mapping, is read so that it can be
    /// refused as "not supported yet" instead of as a YAML type error.
    #[serde(default)]
    pub facet: Option<FacetSpec>,
    /// Labels.
    #[serde(default)]
    pub labs: Labs,
    /// Theme name.
    #[serde(default)]
    pub theme: Option<String>,
}

/// `facet:` of the spec: a name, or anything else (`{wrap: g}`, a list), kept only to refuse it.
#[derive(Debug, Deserialize)]
#[serde(untagged)]
pub enum FacetSpec {
    /// A facet name such as `null` or `wrap`.
    Name(String),
    /// A mapping or a sequence.
    Other(serde::de::IgnoredAny),
}

/// One layer of the spec.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct LayerSpec {
    /// A geom of [`PROVEN_ROWS`].
    pub geom: String,
    /// `identity` when absent.
    #[serde(default)]
    pub stat: Option<String>,
    /// `identity` when absent.
    #[serde(default)]
    pub position: Option<String>,
}

/// `coord:` of the spec.
#[derive(Debug, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct CoordSpec {
    /// `cartesian`.
    #[serde(rename = "type")]
    pub kind: String,
    /// Zoom limits on x, as `coord_cartesian(xlim = )`. Read only to be refused by name: no
    /// ggplot2 row proves them.
    #[serde(default)]
    pub xlim: Option<[f64; 2]>,
    /// Zoom limits on y.
    #[serde(default)]
    pub ylim: Option<[f64; 2]>,
}

/// `labs:` of the spec.
#[derive(Debug, Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Labs {
    /// Title.
    pub title: Option<String>,
    /// x-axis label.
    pub x: Option<String>,
    /// y-axis label.
    pub y: Option<String>,
}

/// Run the verb: build the plot, write it to `--out` or `stdout`, warnings to `stderr`.
///
/// # Errors
///
/// A message for the user: unreadable or malformed input, an unknown column, a non-numeric
/// column, or anything the engine does not support yet (with the supported values).
pub fn run(
    args: &PlotArgs,
    env: &Env,
    stdout: &mut dyn Write,
    stderr: &mut dyn Write,
) -> Result<(), String> {
    let spec = match &args.spec {
        Some(path) => load_spec(path)?,
        None => spec_from_flags(args)?,
    };
    let text = render(&spec, args, env, stderr)?;
    match &args.out {
        Some(path) => {
            std::fs::write(path, text).map_err(|e| format!("cannot write {}: {e}", path.display()))
        }
        None => stdout.write_all(text.as_bytes()).map_err(|e| format!("cannot write stdout: {e}")),
    }
}

fn load_spec(path: &Path) -> Result<Spec, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read spec {}: {e}", path.display()))?;
    let mut spec: Spec = serde_saphyr::from_str(&text)
        .map_err(|e| format!("invalid plot spec {}: {e}", path.display()))?;
    // A relative `data:` is relative to the spec file. `parent()` is `Some` for any file path
    // (`Some("")` for a bare name), and joining an absolute `data:` keeps it as it is.
    let dir = path.parent().unwrap_or(Path::new(""));
    spec.data = dir.join(&spec.data);
    Ok(spec)
}

fn spec_from_flags(args: &PlotArgs) -> Result<Spec, String> {
    // clap guarantees both are present without --spec.
    let data = args.data.clone().map(InputFile::into_path_buf).unwrap_or_default();
    let aes = parse_aes(args.aes.as_ref().map_or("", FreeText::as_str))?;
    let geom = args.geom.clone().map_or_else(|| "point".into(), FreeText::into_string);
    Ok(Spec {
        data,
        aes,
        layers: vec![LayerSpec { geom, stat: None, position: None }],
        ..Spec::default()
    })
}

/// Parse `x=col,y=col` into a mapping.
///
/// # Errors
///
/// A pair without `=`, an empty side, or the same aesthetic twice.
pub fn parse_aes(s: &str) -> Result<BTreeMap<String, String>, String> {
    let mut out = BTreeMap::new();
    for pair in s.split(',').map(str::trim).filter(|p| !p.is_empty()) {
        let (k, v) = pair
            .split_once('=')
            .map(|(k, v)| (k.trim(), v.trim()))
            .filter(|(k, v)| !k.is_empty() && !v.is_empty())
            .ok_or_else(|| format!("--aes: expected aesthetic=column, got '{pair}'"))?;
        if out.insert(k.to_string(), v.to_string()).is_some() {
            return Err(format!("--aes: aesthetic '{k}' is mapped twice"));
        }
    }
    Ok(out)
}

fn refuse(what: &str, got: &str, supported: &[&str]) -> String {
    format!("unsupported {what} '{got}'; supported: {}", supported.join(", "))
}

fn check(what: &str, got: Option<&str>, supported: &[&str]) -> Result<(), String> {
    match got {
        Some(g) if !supported.contains(&g) => Err(refuse(what, g, supported)),
        _ => Ok(()),
    }
}

/// Refuse a facet the engine does not draw (only `null` is).
fn check_facet(facet: Option<&FacetSpec>) -> Result<(), String> {
    match facet {
        None => Ok(()),
        Some(FacetSpec::Name(f)) if facets().contains(&f.as_str()) => Ok(()),
        Some(other) => {
            let got = match other {
                FacetSpec::Name(f) => format!("'{f}'"),
                FacetSpec::Other(_) => "a mapping or a list".into(),
            };
            Err(format!(
                "facets are not supported yet (got {got}); supported: {}",
                facets().join(", ")
            ))
        }
    }
}

/// Validate the spec against what the engine draws, before any data is read.
fn check_spec(spec: &Spec) -> Result<(), String> {
    if spec.layers.is_empty() {
        return Err("the plot has no layers; add one, e.g. geom: point".into());
    }
    for layer in &spec.layers {
        check("geom", Some(&layer.geom), &geoms())?;
        check("stat", layer.stat.as_deref(), &stats(&layer.geom))?;
        check("position", layer.position.as_deref(), &positions(&layer.geom))?;
    }
    for (aes, scale) in &spec.scales {
        check("scale aesthetic", Some(aes), &scale_aesthetics())?;
        check("scale", Some(scale), &scales(aes))?;
    }
    check_facet(spec.facet.as_ref())?;
    check_coord(spec.coord.as_ref())?;
    check("theme", spec.theme.as_deref(), &themes())?;
    for aes in spec.aes.keys() {
        check("aesthetic", Some(aes), &aesthetics())?;
    }
    Ok(())
}

/// The column mapped to aesthetic `a`.
fn mapped_col<'a>(spec: &'a Spec, a: &str) -> Result<&'a String, String> {
    spec.aes.get(a).ok_or_else(|| format!("aes needs a mapping for '{a}' (e.g. {a}=column)"))
}

/// The requested size of the output.
fn output_size(args: &PlotArgs, env: &Env) -> (u32, u32) {
    match args.output {
        Output::Term => term_size(args, env),
        Output::Svg => {
            (args.width.unwrap_or(DEFAULT_SVG_SIZE.0), args.height.unwrap_or(DEFAULT_SVG_SIZE.1))
        }
    }
}

/// Apply title and axis labels; a flag wins over the spec's `labs:`.
fn apply_labs(mut plot: GGPlot, spec: &Spec, args: &PlotArgs) -> GGPlot {
    let labs =
        [(&args.title, &spec.labs.title), (&args.xlab, &spec.labs.x), (&args.ylab, &spec.labs.y)]
            .map(|(flag, spec)| flag.clone().map(FreeText::into_string).or_else(|| spec.clone()));
    let [title, xlab, ylab] = labs;
    if let Some(t) = title {
        plot = plot.title(&t);
    }
    if let Some(t) = xlab {
        plot = plot.xlab(&t);
    }
    if let Some(t) = ylab {
        plot = plot.ylab(&t);
    }
    plot
}

/// Build the plot from the data and the spec.
fn build_plot(
    spec: &Spec,
    row: &ProvenRow,
    (xcol, ycol): (&str, &str),
    (xs, ys): (&[f64], &[f64]),
    args: &PlotArgs,
) -> Result<GGPlot, String> {
    let mut df = DataFrame::new();
    // numeric_xy refused every value outside f32's normal range, so this narrowing keeps the
    // magnitude and loses only digits past f32's 24-bit mantissa.
    let narrow = |v: &[f64]| v.iter().map(|&x| x as f32).collect::<Vec<f32>>();
    df.add_column_f32(xcol, &narrow(xs));
    df.add_column_f32(ycol, &narrow(ys));

    let plot = GGPlot::new().data(df).aes(Aes::new().x(xcol).y(ycol));
    let plot = plot.geom(geom_for(row.geom)?.stat(stat_for(row.stat)?));
    position_for(row.position)?;
    facet_for(row.facet)?;
    aes_for(row.aes)?;
    for (aes, kind) in row.scales {
        scale_for(aes, kind)?;
    }
    let plot = plot.coord(coord_for(row.coord)?).theme(theme_for(row.theme)?);
    Ok(apply_labs(plot, spec, args))
}

/// Render the built plot to the requested target.
fn draw(
    plot: GGPlot,
    args: &PlotArgs,
    env: &Env,
    (width, height): (u32, u32),
) -> Result<String, String> {
    match args.output {
        Output::Term => {
            let color = !args.no_color && !env.no_color && env.stdout_is_tty && args.out.is_none();
            let target = TerminalPlot { width, height, color };
            plot.build().and_then(|b| b.to_terminal(target))
        }
        Output::Svg => plot.dimensions(width, height).build().and_then(|b| b.to_svg()),
    }
    .map_err(|e| e.to_string())
}

/// Validate the spec against what the engine draws, then build and render the plot.
fn render(
    spec: &Spec,
    args: &PlotArgs,
    env: &Env,
    stderr: &mut dyn Write,
) -> Result<String, String> {
    check_spec(spec)?;
    let row = select_row(PROVEN_ROWS, spec)?;
    let (xcol, ycol) = (mapped_col(spec, "x")?, mapped_col(spec, "y")?);
    let size = output_size(args, env);
    // Before the data is read: a size the engine cannot allocate must not cost a read first.
    check_size(args.output, size)?;

    let table = read_csv(&spec.data)?;
    let (xs, ys, dropped) = numeric_xy(&table, xcol, ycol)?;
    if dropped > 0 {
        // ggplot2's wording for the same event.
        let _ = writeln!(stderr, "warning: Removed {dropped} rows containing missing values or values outside the scale range (geom_point).");
    }
    let plot = build_plot(spec, row, (xcol, ycol), (&xs, &ys), args)?;
    draw(plot, args, env, size)
}

/// Check a requested size against the target's bounds: 20x8 to 1000x1000 cells for a terminal,
/// 1x1 to 4096x4096 pixels for SVG.
///
/// # Errors
///
/// The size and the bounds, when either side is outside them.
pub fn check_size(output: Output, (w, h): (u32, u32)) -> Result<(), String> {
    let (kind, unit, min, max) = match output {
        Output::Term => (
            "terminal",
            "cells",
            (MIN_TERMINAL_WIDTH, MIN_TERMINAL_HEIGHT),
            (MAX_TERMINAL_WIDTH, MAX_TERMINAL_HEIGHT),
        ),
        Output::Svg => {
            ("svg", "pixels", (MIN_SVG_SIZE, MIN_SVG_SIZE), (MAX_SVG_SIZE, MAX_SVG_SIZE))
        }
    };
    if (min.0..=max.0).contains(&w) && (min.1..=max.1).contains(&h) {
        return Ok(());
    }
    Err(format!(
        "{kind} plot size must be {}x{} to {}x{} {unit}, got {w}x{h}",
        min.0, min.1, max.0, max.1
    ))
}

/// Terminal size: flags, then `$COLUMNS`/`$LINES` when stdout is a terminal, then 80x24.
fn term_size(args: &PlotArgs, env: &Env) -> (u32, u32) {
    let from_env = |v: &Option<String>| {
        v.as_deref().filter(|_| env.stdout_is_tty).and_then(|s| s.trim().parse::<u32>().ok())
    };
    let w = args.width.or_else(|| from_env(&env.columns)).unwrap_or(DEFAULT_TERM_SIZE.0);
    let h = args.height.or_else(|| from_env(&env.lines)).unwrap_or(DEFAULT_TERM_SIZE.1);
    (w, h)
}

/// A CSV file: header names and the rows below it, each with one field per column.
#[derive(Debug, PartialEq, Eq)]
pub struct Table {
    /// Header names.
    pub columns: Vec<String>,
    /// `(1-based line number, fields)` per data row.
    pub rows: Vec<(usize, Vec<String>)>,
}

fn read_csv(path: &Path) -> Result<Table, String> {
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read data {}: {e}", path.display()))?;
    parse_csv(&text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Parse CSV text: blank lines and lines starting with `#` are skipped; the first other line is
/// the header. Fields may be double-quoted, with `""` for a quote inside.
///
/// # Errors
///
/// No header, an unterminated quote, or a row whose field count differs from the header's.
pub fn parse_csv(text: &str) -> Result<Table, String> {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let mut lines = text
        .lines()
        .enumerate()
        .map(|(i, l)| (i + 1, l.trim_end_matches('\r')))
        .filter(|(_, l)| !l.trim().is_empty() && !l.trim_start().starts_with('#'));
    let (hline, header) = lines.next().ok_or("no header row")?;
    let columns = split_fields(header).map_err(|e| format!("line {hline}: {e}"))?;
    let mut rows = Vec::new();
    for (n, line) in lines {
        let fields = split_fields(line).map_err(|e| format!("line {n}: {e}"))?;
        if fields.len() != columns.len() {
            return Err(format!(
                "line {n}: {} fields, the header has {}",
                fields.len(),
                columns.len()
            ));
        }
        rows.push((n, fields));
    }
    Ok(Table { columns, rows })
}

fn split_fields(line: &str) -> Result<Vec<String>, String> {
    let mut fields = Vec::new();
    let mut cur = String::new();
    let mut chars = line.chars().peekable();
    let mut quoted = false;
    while let Some(c) = chars.next() {
        match (quoted, c) {
            (true, '"') if chars.peek() == Some(&'"') => {
                cur.push('"');
                chars.next();
            }
            (true, '"') => quoted = false,
            (false, '"') if cur.trim().is_empty() => {
                cur.clear();
                quoted = true;
            }
            (false, ',') => fields.push(std::mem::take(&mut cur).trim().to_string()),
            _ => cur.push(c),
        }
    }
    if quoted {
        return Err("unterminated quote".into());
    }
    fields.push(cur.trim().to_string());
    Ok(fields)
}

/// Smallest nonzero magnitude the verb draws.
pub const MIN_MAGNITUDE: f64 = 1e-5;
/// Magnitudes at or above this are refused.
pub const MAX_MAGNITUDE: f64 = 1e16;

/// Zero, or a magnitude in the range whose axis labels were compared with ggplot2 4.0.3: 188
/// ranges, decades 1e-5 to 9.99e15, fixed and scientific notation, all identical (see the
/// contract). It is far inside f32's normal range, so `as f32` keeps the magnitude.
fn in_proven_range(v: f64) -> bool {
    let m = v.abs();
    m == 0.0 || (MIN_MAGNITUDE..MAX_MAGNITUDE).contains(&m)
}

/// A cell ggplot2 would read as missing.
fn is_missing(s: &str) -> bool {
    matches!(s, "" | "NA" | "NaN" | "nan" | "null" | "NULL")
}

/// The mapped x and y columns as `f64`, rows with a missing value in either dropped; also the
/// number dropped.
///
/// # Errors
///
/// A column not in the header (the message lists the columns), a value that is neither a
/// number nor missing (the column is not numeric), or a number outside the proven magnitudes
/// (nonzero below 1e-5, or 1e16 and above).
pub fn numeric_xy(
    table: &Table,
    xcol: &str,
    ycol: &str,
) -> Result<(Vec<f64>, Vec<f64>, usize), String> {
    let index = |name: &str| {
        table.columns.iter().position(|c| c == name).ok_or_else(|| {
            format!("unknown column '{name}'; columns: {}", table.columns.join(", "))
        })
    };
    let (xi, yi) = (index(xcol)?, index(ycol)?);
    let (mut xs, mut ys, mut dropped) = (Vec::new(), Vec::new(), 0);
    for (line, fields) in &table.rows {
        let value = |i: usize, name: &str| -> Result<Option<f64>, String> {
            let s = fields[i].as_str();
            if is_missing(s) {
                return Ok(None);
            }
            match s.parse::<f64>() {
                Ok(v) if v.is_finite() && !in_proven_range(v) => Err(format!(
                    "column '{name}' line {line} has '{s}', outside the magnitudes whose axis \
                     labels are proven against ggplot2 (zero, or {MIN_MAGNITUDE:e} up to but \
                     excluding {MAX_MAGNITUDE:e})"
                )),
                Ok(v) if v.is_finite() => Ok(Some(v)),
                Ok(_) => Ok(None),
                Err(_) => Err(format!(
                    "column '{name}' is not numeric: line {line} has '{s}' (geom_point needs a continuous x and y)"
                )),
            }
        };
        match (value(xi, xcol)?, value(yi, ycol)?) {
            (Some(x), Some(y)) => {
                xs.push(x);
                ys.push(y);
            }
            _ => dropped += 1,
        }
    }
    if xs.is_empty() {
        return Err(format!("no rows with a numeric '{xcol}' and '{ycol}' to plot"));
    }
    Ok((xs, ys, dropped))
}

