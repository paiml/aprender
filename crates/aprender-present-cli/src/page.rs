    fn good() -> String {
        page_html("Demo", "presentar-counter", 800, 600).expect("valid id")
    }

    #[test]
    fn the_loader_only_imports_the_glue_and_starts_it() {
        let boot = boot_module("presentar");
        let code: Vec<&str> = boot
            .lines()
            .filter(|l| !l.starts_with("//") && !l.is_empty())
            .collect();
        assert_eq!(code, ["import init from './presentar.js';", "init();"]);
    }

