//! The page a bundle ships, and the audit that refuses any script the bundle did not generate
//! (aprender#6893).
//!
//! A bundled page carries exactly one script tag, `BOOT_TAG`, which loads `pkg/boot.js`. That
//! file is written by `write_boot_module` from `boot_module`, and all it does is start the wasm
//! module; the app, its input listeners and its frame loop are Rust. Nothing else on the page
//! may run script: no second script tag, no inline body, no `on...` attribute, no
//! `javascript:` URL.
//!
//! Contract: `contracts/present-page-no-script-v1.yaml`.

use std::fs;
use std::io;
use std::path::Path;

/// File name of the generated loader inside `pkg/`.
pub const BOOT_FILE: &str = "boot.js";

/// The one script tag a bundled page may carry.
pub const BOOT_TAG: &str = r#"<script type="module" src="./pkg/boot.js"></script>"#;

/// The canvas the built-in counter mounts on. Must equal `COUNTER_CANVAS_ID` in
/// `aprender-present-lib` (`browser/entry.rs`); a test below reads that file and compares.
pub const COUNTER_CANVAS_ID: &str = "presentar-counter";

/// The generated loader: import the wasm-bindgen glue and start the module. The module's
/// start function does the rest.
#[must_use]
pub fn boot_module(out_name: &str) -> String {
    format!(
        "// Generated by `aprender-present bundle`. Do not edit.\n\
         import init from './{out_name}.js';\n\
         init();\n"
    )
}

/// Write the generated loader into `pkg_dir`.
///
/// # Errors
/// When the directory cannot be made or the file cannot be written.
pub fn write_boot_module(pkg_dir: &Path, out_name: &str) -> io::Result<()> {
    fs::create_dir_all(pkg_dir)?;
    fs::write(pkg_dir.join(BOOT_FILE), boot_module(out_name))
}

fn escape_text(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            other => out.push(other),
        }
    }
    out
}

fn is_plain_id(id: &str) -> bool {
    !id.is_empty()
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_')
}

/// A page with one canvas and the generated loader, and no other script.
///
/// # Errors
/// When `canvas_id` is empty or has a character outside `[A-Za-z0-9_-]`.
pub fn page_html(title: &str, canvas_id: &str, width: u32, height: u32) -> Result<String, String> {
    if !is_plain_id(canvas_id) {
        return Err(format!(
            "canvas id '{canvas_id}' must be one or more of A-Z a-z 0-9 - _"
        ));
    }
    Ok(format!(
        "<!DOCTYPE html>\n\
         <html lang=\"en\">\n\
         <head>\n\
         <meta charset=\"UTF-8\">\n\
         <title>{}</title>\n\
         </head>\n\
         <body>\n\
         <canvas id=\"{canvas_id}\" width=\"{width}\" height=\"{height}\"></canvas>\n\
         {BOOT_TAG}\n\
         </body>\n\
         </html>\n",
        escape_text(title)
    ))
}

/// Advance `at` while `keep` holds, returning the characters passed over.
fn take_while(chars: &[char], at: &mut usize, keep: impl Fn(char) -> bool) -> String {
    let start = *at;
    while *at < chars.len() && keep(chars[*at]) {
        *at += 1;
    }
    chars[start..*at].iter().collect()
}

/// The value after an `=`: quoted (either quote, closing quote consumed) or bare.
fn attribute_value(chars: &[char], at: &mut usize) -> String {
    take_while(chars, at, char::is_whitespace);
    match chars.get(*at).copied() {
        Some(quote @ ('"' | '\'')) => {
            *at += 1;
            let value = take_while(chars, at, |c| c != quote);
            *at = (*at + 1).min(chars.len());
            value
        }
        _ => take_while(chars, at, |c| !c.is_whitespace()),
    }
}

/// One attribute of a tag: lower-cased name and its value (empty when it has none).
fn attributes(tag_body: &str) -> Vec<(String, String)> {
    let chars: Vec<char> = tag_body.chars().collect();
    let mut at = 0;
    let mut found = Vec::new();
    // Skip the tag name.
    take_while(&chars, &mut at, |c| !c.is_whitespace());
    while at < chars.len() {
        take_while(&chars, &mut at, |c| c.is_whitespace() || c == '/');
        let name = take_while(&chars, &mut at, |c| !c.is_whitespace() && c != '=');
        take_while(&chars, &mut at, char::is_whitespace);
        let mut value = String::new();
        if chars.get(at) == Some(&'=') {
            at += 1;
            value = attribute_value(&chars, &mut at);
        }
        if !name.is_empty() {
            found.push((name.to_ascii_lowercase(), value));
        }
    }
    found
}

/// The body of every tag in `html` (the text between `<` and the matching `>`, quotes
/// respected), in order. Closing tags and the doctype are included; callers skip them.
fn tag_bodies(html: &str) -> Vec<String> {
    let mut bodies = Vec::new();
    let mut current: Option<String> = None;
    let mut quote: Option<char> = None;
    for c in html.chars() {
        match (&mut current, quote) {
            (None, _) => {
                if c == '<' {
                    current = Some(String::new());
                }
            }
            (Some(body), Some(open)) => {
                body.push(c);
                if c == open {
                    quote = None;
                }
            }
            (Some(body), None) => {
                if c == '>' {
                    bodies.push(std::mem::take(body));
                    current = None;
                } else {
                    if c == '"' || c == '\'' {
                        quote = Some(c);
                    }
                    body.push(c);
                }
            }
        }
    }
    bodies
}

/// Refuse a page that can run any script other than the generated loader.
///
/// # Errors
/// One line per reason: a script tag that is not `BOOT_TAG`, a missing or repeated loader,
/// an `on...` attribute, or a `javascript:` URL.
pub fn audit_page(html: &str) -> Result<(), Vec<String>> {
    let mut reasons = Vec::new();
    let lower = html.to_ascii_lowercase();
    let script_tags = lower.matches("<script").count();
    let boot_tags = html.matches(BOOT_TAG).count();
    if boot_tags == 0 {
        reasons.push(format!("the generated loader is missing: {BOOT_TAG}"));
    }
    if boot_tags > 1 {
        reasons.push(format!("the generated loader appears {boot_tags} times"));
    }
    if script_tags > boot_tags {
        reasons.push(format!(
            "{} script tag(s) other than the generated loader",
            script_tags - boot_tags
        ));
    }
    for body in tag_bodies(html) {
        if body.starts_with('/') || body.starts_with('!') {
            continue;
        }
        let tag: String = body
            .chars()
            .take_while(|c| !c.is_whitespace())
            .collect::<String>()
            .to_ascii_lowercase();
        for (name, value) in attributes(&body) {
            if name.starts_with("on") {
                reasons.push(format!("<{tag}> has the script attribute '{name}'"));
            }
            let compact: String = value
                .chars()
                .filter(|c| !c.is_whitespace())
                .collect::<String>()
                .to_ascii_lowercase();
            if compact.starts_with("javascript:") {
                reasons.push(format!("<{tag}> {name} is a javascript: URL"));
            }
        }
    }
    if reasons.is_empty() {
        Ok(())
    } else {
        Err(reasons)
    }
}

/// Where the bundled `index.html` came from.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum PageSource {
    /// The project's own page passed the audit and was copied.
    Project,
    /// The project has no page; the counter page was generated.
    Generated,
}

/// Finish a bundle in `output`: write the generated loader and the page. A project page is
/// copied only if it passes `audit_page`; with none, the counter page is generated.
///
/// # Errors
/// The audit's reasons, or one line naming the file that could not be written. On an audit
/// failure no `index.html` is written.
pub fn finish_bundle(
    output: &Path,
    out_name: &str,
    project_page: Option<&str>,
) -> Result<PageSource, Vec<String>> {
    let io_error = |what: &str, e: io::Error| vec![format!("{what}: {e}")];
    let (html, source) = match project_page {
        Some(html) => {
            audit_page(html)?;
            (html.to_string(), PageSource::Project)
        }
        None => (
            page_html("Presentar", COUNTER_CANVAS_ID, 800, 600).map_err(|e| vec![e])?,
            PageSource::Generated,
        ),
    };
    write_boot_module(&output.join("pkg"), out_name)
        .map_err(|e| io_error("cannot write the loader", e))?;
    fs::write(output.join("index.html"), html)
        .map_err(|e| io_error("cannot write index.html", e))?;
    Ok(source)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::path::PathBuf;

    fn scratch(name: &str) -> PathBuf {
        let dir = std::env::temp_dir().join(format!("present-page-{name}-{}", std::process::id()));
        let _ = fs::remove_dir_all(&dir);
        fs::create_dir_all(&dir).expect("scratch dir");
        dir
    }

    fn good() -> String {
        page_html("Demo", "presentar-counter", 800, 600).expect("valid id")
    }

    #[test]
    fn the_loader_only_imports_the_glue_and_starts_it() {
        let boot = boot_module("presentar");
        let code: Vec<&str> = boot
            .lines()
            .filter(|l| !l.starts_with("//") && !l.is_empty())
            .collect();
        assert_eq!(code, ["import init from './presentar.js';", "init();"]);
    }

    #[test]
    fn the_generated_page_passes_its_own_audit() {
        let page = good();
        assert_eq!(audit_page(&page), Ok(()));
        assert_eq!(page.matches("<script").count(), 1);
        assert!(page.contains(r#"<canvas id="presentar-counter" width="800" height="600">"#));
    }

    #[test]
    fn the_title_is_escaped() {
        let page = page_html(r#"a<script>&"b">"#, "c", 1, 1).expect("valid id");
        assert!(page.contains("<title>a&lt;script&gt;&amp;&quot;b&quot;&gt;</title>"));
        assert_eq!(audit_page(&page), Ok(()));
    }

    #[test]
    fn a_canvas_id_that_could_break_out_of_the_attribute_is_refused() {
        for bad in ["", "a b", "a\"b", "a>b", "a'b", "é"] {
            assert!(page_html("t", bad, 1, 1).is_err(), "{bad:?}");
        }
        for ok in ["a", "A-1_b", "presentar-counter"] {
            assert!(page_html("t", ok, 1, 1).is_ok(), "{ok:?}");
        }
    }

    /// Case table (must refuse / must accept). Each refused row is the good page with one
    /// change, so the row fails for that change alone.
    #[test]
    fn audit_case_table() {
        let good = good();
        let with = |extra: &str| good.replace("</body>", &format!("{extra}\n</body>"));
        let refuse: Vec<(&str, String, &str)> = vec![
            (
                "inline script",
                with("<script>alert(1)</script>"),
                "other than",
            ),
            (
                "second module",
                with(r#"<script type="module" src="./app.js"></script>"#),
                "other than",
            ),
            ("upper-case tag", with("<SCRIPT>x()</SCRIPT>"), "other than"),
            (
                "loader with a body",
                good.replace(
                    BOOT_TAG,
                    r#"<script type="module" src="./pkg/boot.js">x()</script>"#,
                ),
                "missing",
            ),
            (
                "loader from elsewhere",
                good.replace("./pkg/boot.js", "https://example.com/boot.js"),
                "missing",
            ),
            ("no loader", good.replace(BOOT_TAG, ""), "missing"),
            ("loader twice", with(BOOT_TAG), "2 times"),
            (
                "onclick",
                with(r#"<button onclick="go()">x</button>"#),
                "'onclick'",
            ),
            (
                "upper-case handler",
                with(r#"<img src="a.png" ONERROR=go()>"#),
                "'onerror'",
            ),
            (
                "handler after a quoted >",
                with(r#"<a title="a>b" onmouseover='go()'>x</a>"#),
                "'onmouseover'",
            ),
            (
                "javascript: URL",
                with(r#"<a href="javascript:go()">x</a>"#),
                "javascript: URL",
            ),
            (
                "javascript: URL in disguise",
                with("<a href=\" Java\tScript:go()\">x</a>"),
                "javascript: URL",
            ),
            (
                "spaces around the equals sign",
                with("<a href = \"javascript:go()\">x</a>"),
                "javascript: URL",
            ),
            (
                "self-closing with a handler",
                with(r#"<body2 onload="go()"/>"#),
                "'onload'",
            ),
        ];
        for (name, page, expect) in &refuse {
            let reasons = audit_page(page).expect_err(name);
            assert!(
                reasons.iter().any(|r| r.contains(expect)),
                "{name}: {reasons:?}"
            );
        }
        let accept: Vec<(&str, String)> = vec![
            ("the generated page", good.clone()),
            (
                "a word starting with on in text",
                with("<p>once only, onclick=\"x\" is text here</p>"),
            ),
            (
                "an attribute value that mentions onclick",
                with(r#"<p title="onclick=go()">x</p>"#),
            ),
            (
                "a link that mentions javascript later",
                with(r#"<a href="https://example.com/javascript:intro">x</a>"#),
            ),
            (
                "a bare attribute and a video",
                with(r#"<video src="a.mp4" controls muted></video>"#),
            ),
            (
                "an unquoted value",
                with("<canvas id=wave width=640 height=120></canvas>"),
            ),
        ];
        for (name, page) in &accept {
            assert_eq!(audit_page(page), Ok(()), "{name}");
        }
    }

    #[test]
    fn a_page_cut_off_inside_a_tag_or_a_quote_is_judged_on_what_is_there() {
        assert!(audit_page("<p title=\"never closed").is_err());
        assert!(audit_page("<p onclick").is_err());
        let cut = format!("{}<p title='x", good());
        assert_eq!(audit_page(&cut), Ok(()));
    }

    #[test]
    fn a_bundle_with_no_project_page_gets_the_counter_page_and_the_loader() {
        let out = scratch("generated");
        assert_eq!(
            finish_bundle(&out, "presentar", None),
            Ok(PageSource::Generated)
        );
        let page = fs::read_to_string(out.join("index.html")).expect("page");
        assert_eq!(audit_page(&page), Ok(()));
        assert!(page.contains(COUNTER_CANVAS_ID));
        let boot = fs::read_to_string(out.join("pkg").join(BOOT_FILE)).expect("loader");
        assert_eq!(boot, boot_module("presentar"));
        let _ = fs::remove_dir_all(&out);
    }

    #[test]
    fn a_clean_project_page_is_copied_unchanged() {
        let out = scratch("project");
        let page = good().replace("Demo", "Mine");
        assert_eq!(
            finish_bundle(&out, "presentar", Some(&page)),
            Ok(PageSource::Project)
        );
        assert_eq!(
            fs::read_to_string(out.join("index.html")).expect("page"),
            page
        );
        let _ = fs::remove_dir_all(&out);
    }

    #[test]
    fn a_project_page_with_script_is_refused_and_nothing_is_written() {
        let out = scratch("refused");
        let page = good().replace("</body>", "<script>x()</script></body>");
        let reasons = finish_bundle(&out, "presentar", Some(&page)).expect_err("refused");
        assert!(reasons[0].contains("other than"), "{reasons:?}");
        assert!(!out.join("index.html").exists());
        assert!(!out.join("pkg").exists());
        let _ = fs::remove_dir_all(&out);
    }

    #[test]
    fn a_bundle_that_cannot_be_written_says_which_file() {
        let out = scratch("unwritable");
        // `pkg` is a file, so the loader's directory cannot be made.
        fs::write(out.join("pkg"), "x").expect("blocker");
        let reasons = finish_bundle(&out, "presentar", None).expect_err("blocked");
        assert!(
            reasons[0].starts_with("cannot write the loader"),
            "{reasons:?}"
        );
        fs::remove_file(out.join("pkg")).expect("unblock");
        // `index.html` is a directory, so the page cannot be written.
        fs::create_dir_all(out.join("index.html")).expect("blocker");
        let reasons = finish_bundle(&out, "presentar", None).expect_err("blocked");
        assert!(
            reasons[0].starts_with("cannot write index.html"),
            "{reasons:?}"
        );
        let _ = fs::remove_dir_all(&out);
    }

    /// The canvas id is spelled twice (here and in the wasm crate, which this CLI does not
    /// link). Changing one without the other fails here.
    #[test]
    fn the_counter_canvas_id_matches_the_wasm_crate() {
        let entry = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
            .join("../aprender-present-lib/src/browser/entry.rs");
        let text = fs::read_to_string(&entry).expect("entry.rs");
        assert!(text.contains(&format!(
            "pub const COUNTER_CANVAS_ID: &str = \"{COUNTER_CANVAS_ID}\";"
        )));
    }
}
